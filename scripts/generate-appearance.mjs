import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {SKINS} from '../src/shared/appearance/skins.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const header = 'Generated by scripts/generate-appearance.mjs. Edit skins.config.json and add assets, then run npm run build.';

/** Pure generation is also used by the extension regression with a seventh, config-only skin. */
export async function generateAppearanceFiles(skins, assetDir = path.join(root, 'src/renderer/src/assets/skins')) {
  const quote = JSON.stringify;
  const colors = `/* ${header} */\n` + skins.map(skin => {
    const entries = Object.entries(skin.colors).filter(([key])=>skin.id !== 'classic' || ['--bg-hover','--bg-active','--bg-active-hover'].includes(key));
    return `html[data-skin=${quote(skin.id)}] {\n${entries.map(([key,value])=>`  ${key}: ${value};`).join('\n')}\n}`;
  }).join('\n\n') + '\nhtml[data-color-mode="light"] { color-scheme: light; }\nhtml[data-appearance-ready="false"] #root { visibility: hidden; }\nhtml[data-window="orb"], html[data-window="caption"], html[data-window="task-popover"] { background: transparent !important; }\n';
  const bootstrap = `/* ${header} */
(() => {
  const html=document.documentElement;
  const ids=${quote(skins.map(skin=>skin.id))};
  const bootstrap=window.hemiVoice?.getAppearanceBootstrap?.();
  const skin=bootstrap?.snapshot?.preference?.skinId;
  html.dataset.skin=ids.includes(skin)?skin:'classic';html.dataset.colorMode='light';
  const mode=bootstrap?.windowMode||new URLSearchParams(location.search).get('mode')||'main';html.dataset.window=['orb','caption','task-popover'].includes(mode)?mode:'main';
  html.dataset.appearanceReady='false';
  html.style.backgroundColor=bootstrap?.backgroundColor||(html.dataset.window==='main'?${quote(skins[0].windowBackground)}:'transparent');
  const meta=document.querySelector('meta[name="theme-color"]');if(meta&&bootstrap)meta.content=bootstrap.backgroundColor;
})();
`;
  const declaration = `// ${header}
export type SkinId=${skins.map(skin=>quote(skin.id)).join('|')};
export type SkinMediaDefinition={readonly image:string;readonly portrait:string;readonly motion:string;readonly width:number;readonly height:number;readonly paddingX:number;readonly paddingY:number;readonly durationMs:number;readonly framesPerSecond:number;readonly motionKind:string};
export type SkinDefinition={readonly id:SkinId;readonly name:string;readonly windowBackground:string;readonly headline:string|null;readonly subline:string|null;readonly assets:SkinMediaDefinition|null;readonly colors:Readonly<Record<string,string>>};
export const SKINS:readonly SkinDefinition[];
export const SKIN_IDS:readonly SkinId[];
export function getSkin(id:unknown):SkinDefinition;
`;
  const imports = [], mappings = [], records = {};
  for (const [index,skin] of skins.entries()) {
    if (!skin.assets) continue;
    const asset = skin.assets, files = {};
    for (const kind of ['image','portrait','motion']) {
      const name = asset[kind], bytes = await fs.readFile(path.join(assetDir,name)).catch(error=>{throw new Error(`${skin.id}: missing ${kind} asset ${name}`, {cause:error});});
      if (!bytes.length) throw new Error(`${skin.id}: empty ${kind} asset ${name}`);
      files[name] = {bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};
      imports.push(`import skin${index}${kind} from ${quote(`@/assets/skins/${name}`)};`);
    }
    mappings.push(`  ${quote(skin.id)}:{image:skin${index}image,portrait:skin${index}portrait,motion:skin${index}motion,width:${asset.width},height:${asset.height},paddingX:${asset.paddingX},paddingY:${asset.paddingY}},`);
    records[skin.id] = {width:asset.width,height:asset.height,padding:{x:asset.paddingX,y:asset.paddingY},durationMs:asset.durationMs,framesPerSecond:asset.framesPerSecond,motion:asset.motionKind,files};
  }
  const assets = `// ${header}
${imports.join('\n')}
import type {SkinId} from '@shared/appearance/types';
export type SkinAssets={image:string;portrait:string;motion:string;width:number;height:number;paddingX:number;paddingY:number};
export const skinAssets:Readonly<Partial<Record<SkinId,SkinAssets>>>={
${mappings.join('\n')}
};
export const assetsFor=(id:SkinId):SkinAssets|null=>skinAssets[id]??null;
`;
  return new Map([
    ['src/renderer/public/appearance-colors.css',colors],
    ['src/renderer/public/appearance-bootstrap.js',bootstrap],
    ['src/shared/appearance/skins.d.mts',declaration],
    ['src/renderer/src/appearance/assets.ts',assets],
    ['src/renderer/src/assets/skins/manifest.json',JSON.stringify({version:1,generatedBy:'scripts/generate-appearance.mjs',skins:records},null,2)+'\n'],
  ]);
}

async function main() {
  // Validate every asset before writing any output; malformed additions cannot partially update generated files.
  const files = await generateAppearanceFiles(SKINS), stale = [];
  for (const [relative,content] of files) {
    const file = path.join(root,relative), previous = await fs.readFile(file,'utf8').catch(error=>{if(error.code==='ENOENT')return null;throw error;});
    if (previous === content) continue;
    if (process.argv.includes('--check')) stale.push(relative);
    else await fs.writeFile(file,content);
  }
  if (stale.length) throw new Error(`Generated appearance files are stale: ${stale.join(', ')}. Run node scripts/generate-appearance.mjs.`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
