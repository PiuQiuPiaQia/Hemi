// UI 展示专项；固定账本 fixtures，不证明 provider 计费或 agent 执行路径。
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const runtime = path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs');
const { chromium } = await import(pathToFileURL(runtime).href);
const base = process.env.HEMI_VERIFY_BASE || 'http://127.0.0.1:5173';
const label = process.env.HEMI_VERIFY_LABEL || 'dev';
const output = path.resolve(`.visual/workflow/vision/048-usage-${label}`);
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const errors = [];
const checks = [];
const pass = (name) => { checks.push(name); console.log(`PASS ${name}`); };
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
const go = async (scene, variant = '') => {
  await page.mouse.move(0, 0);
  await page.goto(`${base}/fixtures.html?scene=${scene}${variant ? `&variant=${variant}` : ''}`);
  await page.waitForTimeout(350);
};
const panel = page.locator('.h48-usage-panel');
const entry = page.locator('.h48-usage-entry');
const shot = (name) => page.screenshot({ path: path.join(output, `${name}.png`) });
const fit = async () => {
  const bounds = await page.locator('.h37-info-popover').boundingBox();
  const viewport = page.viewportSize();
  assert(bounds && bounds.x >= -1 && bounds.y >= -1 && bounds.x + bounds.width <= viewport.width + 1 && bounds.y + bounds.height <= viewport.height + 1, JSON.stringify(bounds));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '页面不能横向溢出');
};
try {
  for (const width of [1440, 768, 375]) {
    await page.setViewportSize({ width, height: 900 });
    await go('usage-entry');
    const geometry = await page.evaluate(() => {
      const composer = document.querySelector('.h24-composer').getBoundingClientRect();
      const input = document.querySelector('.text-composer').getBoundingClientRect();
      const footer = document.querySelector('.h48-usage-entry').getBoundingClientRect();
      return { composer: composer.toJSON(), input: input.toJSON(), footer: footer.toJSON() };
    });
    assert(geometry.footer.y >= geometry.input.bottom - 1, '预览在输入框下方');
    assert(geometry.footer.bottom <= geometry.composer.bottom + 1, '复用底部留白');
    assert(Math.abs(geometry.footer.x + geometry.footer.width / 2 - geometry.input.x - geometry.input.width / 2) <= 1, '预览在输入框下居中');
    assert(geometry.composer.bottom - geometry.input.bottom <= 21, JSON.stringify(geometry));
    assert((await entry.innerText()).includes('缓存命中'));
    assert((await entry.innerText()).includes('token/s'));
    await shot(`footer-${width}`);
    await page.locator('textarea[aria-label=输入消息]').focus();
    await entry.hover();
    await panel.waitFor({ state: 'visible' });
    assert(await page.locator('textarea[aria-label=输入消息]').evaluate(el => el === document.activeElement), '悬浮不抢输入焦点');
    assert.equal(await panel.locator('.h37-info-close').count(), 0, '悬浮预览没有叉号');
    await page.waitForTimeout(250);
    await fit();
    await shot(`footer-open-${width}`);
    await panel.hover();
    const totalsBefore = await panel.locator('.h48-usage-totals').innerText();
    const beforeSwitch = await panel.boundingBox();
    await panel.getByRole('button', { name: '模型', exact: true }).click();
    await page.waitForTimeout(450);
    assert.equal(await panel.getByRole('button', { name: '模型', exact: true }).getAttribute('aria-pressed'), 'true');
    assert.equal(await panel.locator('thead th').first().innerText(), '模型');
    assert.equal(await panel.getByRole('table', { name: '各模型用量' }).isVisible(), true);
    const modelRows = await panel.locator('tbody tr').allTextContents();
    assert.equal(modelRows.length, 2, '主助手与辅助共用的准确模型合并为一行');
    assert.deepEqual(await panel.locator('tbody tr td:first-of-type').allTextContents(), ['7', '2']);
    assert.equal(await panel.locator('.h48-usage-totals').innerText(), totalsBefore);
    const afterSwitch = await panel.boundingBox();
    assert(Math.abs(beforeSwitch.y - afterSwitch.y) <= 1 && Math.abs(beforeSwitch.height - afterSwitch.height) <= 1, '切换时面板不跳位');
    await fit();
    await shot(`models-${width}`);
    await panel.getByRole('button', { name: '角色', exact: true }).click();
    assert.equal(await panel.locator('tbody tr').count(), 3);
    await page.waitForTimeout(450);
    assert(await panel.isVisible(), '移入弹窗保持显示');
    await entry.click();
    await page.mouse.move(0, 0);
    await panel.waitFor({ state: 'detached' });
    await page.keyboard.press('Tab');
    await entry.focus();
    await panel.waitFor({ state: 'visible' });
    await page.keyboard.press('Escape');
    await panel.waitFor({ state: 'detached' });
    assert(await entry.evaluate(el => el === document.activeElement), '键盘聚焦查看，Esc 保持入口焦点');
    await page.locator('textarea[aria-label=输入消息]').focus();
    await page.keyboard.press('Tab');
    await entry.focus();
    await panel.waitFor({ state: 'visible' });
    const keyboardModel = panel.getByRole('button', { name: '模型', exact: true });
    // mac 默认 Tab 只巡航文本；Option+Tab 按原生口径巡航按钮。
    for (let i = 0; i < 8 && !await keyboardModel.evaluate(el => el === document.activeElement); i++) await page.keyboard.press('Alt+Tab');
    assert(await keyboardModel.evaluate(el => el === document.activeElement), '键盘能从预览进入切换控件');
    await page.keyboard.press('Enter');
    assert.equal(await panel.locator('thead th').first().innerText(), '模型');
    await page.keyboard.press('Escape');
    await panel.waitFor({ state: 'detached' });
    const scope = page.getByRole('button', { name: /^访问范围：/ });
    await scope.click();
    await page.getByRole('dialog', { name: '访问范围' }).waitFor({ state: 'visible' });
    await page.waitForTimeout(250);
    await fit();
    await shot(`scope-${width}`);
    await page.getByRole('button', { name: '关闭访问范围', exact: true }).click();
    await page.getByRole('dialog', { name: '访问范围' }).waitFor({ state: 'detached' });
    pass(`${width}：居中悬浮／角色模型切换／键盘／无跳位／访问范围回归`);
  }

  await page.setViewportSize({ width: 1440, height: 900 });
  await go('usage-panel');
  assert((await panel.innerText()).includes('1,250 次调用'));
  assert.equal(await panel.locator('details, summary').count(), 0, '不折叠、不放统计说明');
  assert.equal(await panel.getByRole('table', { name: '各角色用量' }).isVisible(), true);
  assert.deepEqual(await panel.locator('tbody th').allTextContents(), ['主助手', '顾问', '执行', '设计']);
  assert.deepEqual(await panel.locator('.h48-usage-total b').allTextContents(), ['52M', '559k', '136 token/s', '98%']);
  assert.equal(await panel.locator('tbody tr').last().locator('td').nth(1).innerText(), '—');
  assert(!(await panel.innerText()).includes('统计说明'));
  assert(!(await panel.innerText()).includes('费用'));
  await shot('panel-1440');
  pass('整体数据与角色表格直接可见，无说明文案；未知用量不写零');

  const closing = await page.evaluate(() => {
    window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    return new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(() => {
      const node = document.querySelector('.h48-usage-panel');
      resolve(node && { ending: node.hasAttribute('data-ending-style'), duration: getComputedStyle(node).transitionDuration });
    })));
  });
  assert(closing?.ending && closing.duration.includes('0.14s'), JSON.stringify(closing));
  await panel.waitFor({ state: 'detached' });
  await entry.hover();
  await panel.waitFor({ state: 'visible' });
  await page.mouse.move(0, 0);
  await page.waitForTimeout(170);
  await entry.hover();
  await page.waitForTimeout(500);
  assert.equal(await panel.count(), 1);
  assert.equal(await entry.getAttribute('aria-expanded'), 'true');
  await page.mouse.move(0, 0);
  await panel.waitFor({ state: 'detached' });
  pass('退出 140ms 节点保留／快速开关反向／重开无残留');

  await go('usage-entry');
  await entry.hover();
  await panel.waitFor({ state: 'visible' });
  const outside = page.getByRole('button', { name: '新建对话', exact: true });
  await outside.click();
  await panel.waitFor({ state: 'detached' });
  assert(await outside.evaluate(el => el === document.activeElement), '点外不抢焦');
  pass('点外关闭保留用户新焦点');

  for (const width of [768, 375]) {
    await page.setViewportSize({ width, height: 900 });
    await go('usage-panel');
    await fit();
    assert(await panel.locator('.h48-usage-table').evaluate(el => el.scrollWidth <= el.clientWidth), '表格不横向溢出');
    await shot(`panel-${width}`);
    await panel.getByRole('button', { name: '模型', exact: true }).click();
    await fit();
    assert(await panel.locator('.h48-usage-table').evaluate(el => el.scrollWidth <= el.clientWidth), '模型表格不溢出');
    assert(await panel.locator('.h48-usage-name').evaluateAll(nodes => nodes.every(el => el.title === el.textContent)), '模型完整名称保留');
    await shot(`panel-models-${width}`);
    await panel.getByRole('button', { name: '角色', exact: true }).click();
    assert.equal(await panel.getAttribute('aria-modal'), null, '只读悬浮不锁定对话');
    pass(`${width}：角色表格完整可见、窄窗操作`);
  }

  await page.setViewportSize({ width: 375, height: 320 });
  await go('usage-panel', 'many');
  await fit();
  const scroll = panel.locator('.h48-usage-detail');
  assert(await scroll.evaluate(el => el.scrollHeight > el.clientHeight));
  await scroll.evaluate(el => { el.scrollTop = el.scrollHeight; });
  await shot('roles-scroll-375');
  await panel.getByRole('button', { name: '模型', exact: true }).click();
  const modelScroll = panel.locator('.h48-usage-detail');
  assert(await modelScroll.evaluate(el => el.scrollHeight > el.clientHeight), '多模型表内滚动');
  assert.equal(await panel.locator('tbody tr').count(), 24);
  await modelScroll.evaluate(el => { el.scrollTop = el.scrollHeight; });
  const summaryBounds = await panel.locator('.h48-usage-totals').boundingBox();
  const modelHeaderBounds = await panel.locator('thead').boundingBox();
  assert(modelHeaderBounds.y >= summaryBounds.y + summaryBounds.height, '表内滚动时汇总与列头仍完整可见');
  await shot('models-scroll-375');
  assert.equal(await panel.locator('.h37-info-close').count(), 0);
  await page.keyboard.press('Escape');
  await panel.waitFor({ state: 'detached' });
  pass('小高度角色统计可滚动，无叉号且可用 Esc 关闭');
  await page.setViewportSize({ width: 375, height: 900 });

  await go('usage-panel', 'unknown');
  assert.deepEqual(await panel.locator('.h48-usage-total b').allTextContents(), ['—', '—', '—', '—']);
  assert.equal(await panel.locator('tbody tr').getAttribute('title'), '31 次调用未返回用量');
  await shot('unknown-375');
  await go('usage-panel', 'error');
  assert(await panel.getByRole('status').isVisible());
  await shot('error-375');
  await go('usage-panel', 'empty');
  assert.equal(await entry.count(), 0);
  pass('全缺失／加载失败／空账本边界');

  await page.emulateMedia({ reducedMotion: 'reduce' });
  await go('usage-panel');
  assert.equal(await panel.evaluate(el => getComputedStyle(el).transform), 'none');
  await shot('reduced-motion-375');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await go('usage-panel', 'design');
  const design = await panel.boundingBox();
  assert.equal(design.width, 500);
  assert(design.height <= 270, JSON.stringify(design));
  const heading = await panel.locator('.h37-info-title').boundingBox();
  const count = await panel.locator('.h37-info-description').boundingBox();
  assert(Math.abs(heading.y - count.y) <= 5, '标题与调用次数同排');
  assert.equal(await panel.locator('tbody tr').count(), 5);
  assert.deepEqual(await panel.locator('.h48-usage-total b').allTextContents(), ['52M', '558k', '137 token/s', '97%']);
  assert.equal(await panel.locator('table .h48-usage-totals').count(), 0);
  await panel.screenshot({ path: path.join(output, 'v4-popover-only.png') });
  await shot('v4-1440');
  await panel.getByRole('button', { name: '模型', exact: true }).click();
  await panel.screenshot({ path: path.join(output, 'model-popover-only.png') });
  pass(`v4：独立汇总带／标题同排／五角色局部 ${design.width}×${design.height}`);
  const touch = await browser.newPage({ viewport: { width: 375, height: 900 }, hasTouch: true, isMobile: true });
  touch.on('pageerror', error => errors.push(error.message));
  await touch.goto(`${base}/fixtures.html?scene=usage-entry`);
  const touchEntry = touch.locator('.h48-usage-entry');
  await touchEntry.tap();
  await touch.locator('.h48-usage-panel').waitFor({ state: 'visible' });
  await touch.getByRole('button', { name: '模型', exact: true }).tap();
  assert.equal(await touch.locator('.h48-usage-table').getAttribute('data-dimension'), 'model');
  await touch.getByRole('button', { name: '角色', exact: true }).tap();
  assert.equal(await touch.locator('.h48-usage-table').getAttribute('data-dimension'), 'role');
  await touchEntry.tap();
  await touch.locator('.h48-usage-panel').waitFor({ state: 'detached' });
  await touch.close();
  pass('触屏点击仍可打开与收起');
  assert.deepEqual(errors, []);
  pass('减少动态效果无位移，console／React 错误为零');
  await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ base, label, checks, errors }, null, 2));
} finally {
  await browser.close();
}
